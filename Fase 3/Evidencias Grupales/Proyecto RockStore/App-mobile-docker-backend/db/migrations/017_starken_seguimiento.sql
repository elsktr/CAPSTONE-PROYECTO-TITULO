-- Estado del seguimiento informado por Starken y dueño de cada reintento de emisión.
-- Las columnas nuevas son nullable: los pedidos ya despachados adquieren estado al sincronizar.

ALTER TABLE logistica.pedidos
  ADD COLUMN seguimiento_estado text,
  ADD COLUMN seguimiento_actualizado_en timestamptz;

ALTER TABLE logistica.despachos_pendientes
  ADD COLUMN id_usuario integer REFERENCES usuarios.usuarios;

-- Historial de lo que dice el transportista. La llave evita duplicar eventos si dos
-- réplicas consultan el mismo envío al mismo tiempo.
CREATE TABLE logistica.seguimiento_eventos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo text NOT NULL,
  estado text NOT NULL CHECK (estado IN ('PREPARADO', 'EN_TRANSITO', 'ENTREGADO')),
  descripcion text NOT NULL,
  fecha_evento timestamptz NOT NULL,
  consultado_en timestamptz NOT NULL DEFAULT now(),
  UNIQUE (codigo, estado, fecha_evento)
);

CREATE INDEX seguimiento_eventos_por_codigo_fecha ON logistica.seguimiento_eventos (codigo, fecha_evento);

-- Tarifas de respaldo iniciales, para cotizar aunque Starken no responda y no haya caché.
-- No pisan las que el Gerente haya definido antes.
INSERT INTO logistica.tarifas_respaldo (zona, tramo_peso, valor)
SELECT zona, tramo, base + (tramo - 1) * 500
FROM (VALUES ('SANTIAGO', 3990), ('REGIONES', 7990)) AS tarifas(zona, base)
CROSS JOIN generate_series(1, 5) AS tramo
ON CONFLICT (zona, tramo_peso) DO NOTHING;
